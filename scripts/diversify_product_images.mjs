async function main() {
  console.log('=== MULTI-PROVIDER CATALOG DIVERSIFICATION START ===');
  const client = await pool.connect();

  try {
    // 1. Fetch all products grouped by category
    const res = await client.query(`
      SELECT p.id, p.name, p.slug, c.name as category_name
      FROM "products" p
      LEFT JOIN "categories" c ON p."categoryId" = c.id
      ORDER BY c.name, p.name
    `);

    console.log(`Retrieved ${res.rows.length} products from database.`);

    const byCategory = {};
    res.rows.forEach(p => {
      const cat = p.category_name || 'Tech & Electronics';
      byCategory[cat] = byCategory[cat] || [];
      byCategory[cat].push(p);
    });

    let totalUpdated = 0;

    for (const [catName, products] of Object.entries(byCategory)) {
      if (catName === 'Electronics') {
        // Single flagship item, keep pristine
        continue;
      }

      const poolUrls = DIVERSE_CATEGORY_IMAGES[catName] || DIVERSE_CATEGORY_IMAGES['Tech & Electronics'];
      console.log(`\nProcessing category: "${catName}" (${products.length} products, ${poolUrls.length} available pool images)...`);

      if (poolUrls.length < products.length) {
        console.warn(`Warning: pool has ${poolUrls.length} images for ${products.length} products. Expanding...`);
      }

      for (let i = 0; i < products.length; i++) {
        const prod = products[i];
        // Assign 100% unique primary image index
        const primaryImg = poolUrls[i % poolUrls.length];
        // Assign a distinct secondary image index (offset by half the pool size)
        const secondaryImg = poolUrls[(i + Math.floor(poolUrls.length / 2)) % poolUrls.length];

        const updatedImages = [primaryImg, secondaryImg];

        await client.query(`
          UPDATE "products"
          SET "images" = $1, "updatedAt" = NOW()
          WHERE "id" = $2
        `, [updatedImages, prod.id]);

        totalUpdated++;
      }
      console.log(`✓ Updated all ${products.length} products in "${catName}" with unique multi-provider images.`);
    }

    console.log(`\nSuccessfully updated ${totalUpdated} products across all categories.`);

    // 2. Verification query
    const auditRes = await client.query(`
      SELECT c.name as category_name, count(p.id) as total_products, count(distinct p.images[1]) as distinct_primary_images
      FROM "products" p
      LEFT JOIN "categories" c ON p."categoryId" = c.id
      GROUP BY c.name
      ORDER BY total_products DESC
    `);

    console.log('\n--- VERIFICATION AUDIT RESULTS ---');
    console.table(auditRes.rows);

  } catch (err) {
    console.error('Migration failed:', err);
    process.exit(1);
  } finally {
    client.release();
    await pool.end();
  }
}

main();
